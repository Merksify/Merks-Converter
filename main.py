import os
import sys
from pathlib import Path
from PIL import Image

def clean_file_path(path_str):
    cleaned = path_str.strip().strip("'\"")
    cleaned = cleaned.replace("\ ", " ")
    return Path(cleaned)

def convert_file(input_path: Path, target_ext: str):
    target_ext = target_ext.strip().lower()
    if not target_ext.startswith("."):
        target_ext = "." + target_ext

    if not input_path.exists() or not input_path.is_file():
        print(f"\n[Error] File '{input_path}' does not exist.\n")
        return

    output_path = input_path.with_suffix(target_ext)

    try:
        with Image.open(input_path) as img:
            if img.mode in ("RGBA", "P") and target_ext in [".jpg", ".jpeg"]:
                img = img.convert("RGB")
            img.save(output_path)
            print(f"\nSuccess! File saved to:\n  {output_path}\n")
    except Exception as e:
        print(f"\n[Error] Conversion failed: {e}\n")

